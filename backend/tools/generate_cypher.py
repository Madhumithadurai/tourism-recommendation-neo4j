def s(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(s(x) for x in v) + "]"
    if isinstance(v, dict):                                   # nested maps, e.g. a tourist's interests
        return "{" + ", ".join(f"{k}: {s(x)}" for k, x in v.items()) + "}"
    text = str(v)
    if ";" in text:
        raise ValueError(f"Remove ';' from {text!r} (scripts are split on ';').")
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def rows(items):
    return "[\n" + ",\n".join("  {" + ", ".join(f"{k}: {s(v)}" for k, v in d.items()) + "}" for d in items) + "\n]"


def constraints():
    return """// =====================================================================
// TripGraph - Tourism Recommendation System using Neo4j
// Script 01: uniqueness constraints and indexes (Neo4j 5.x). Safe to run again.
// =====================================================================

// STEP 1: Uniqueness constraints
// One unique key per label. Each constraint also creates an index used by MATCH and MERGE.
CREATE CONSTRAINT tourist_id IF NOT EXISTS FOR (t:Tourist) REQUIRE t.touristId IS UNIQUE;
CREATE CONSTRAINT destination_name IF NOT EXISTS FOR (d:Destination) REQUIRE d.name IS UNIQUE;
CREATE CONSTRAINT attraction_id IF NOT EXISTS FOR (a:Attraction) REQUIRE a.attractionId IS UNIQUE;
CREATE CONSTRAINT category_name IF NOT EXISTS FOR (c:Category) REQUIRE c.name IS UNIQUE;
CREATE CONSTRAINT hotel_id IF NOT EXISTS FOR (h:Hotel) REQUIRE h.hotelId IS UNIQUE;

// STEP 2: Extra indexes for lookups by name
CREATE INDEX attraction_name IF NOT EXISTS FOR (a:Attraction) ON (a.name);
CREATE INDEX hotel_band IF NOT EXISTS FOR (h:Hotel) ON (h.priceBand);
"""


def sample():
    out = ["""// =====================================================================
// TripGraph - Tourism Recommendation System using Neo4j
// Script 02: sample data population (South India).
// Destinations and attractions are real places, coordinates approximate.
// Distances, hours and costs are rounded illustrative estimates. Hotels and tourists are fictional.
// MERGE is used everywhere, so the script can be run again without creating duplicates.
// Generated by backend/tools/generate_cypher.py from backend/data/tourism.py
// =====================================================================
"""]
    out.append("// STEP 1: Categories (interest tags)")
    out.append(f"UNWIND {s(T.CATEGORIES)} AS name\nMERGE (:Category {{name: name}});\n")

    out.append("// STEP 2: Destinations with coordinates and best months to visit")
    ds = [{"name": n, "state": st, "lat": la, "lon": lo, "months": m, "description": de} for n, st, la, lo, m, de in T.DESTINATIONS]
    out.append(f"UNWIND {rows(ds)} AS d\nMERGE (x:Destination {{name: d.name}})\n"
               "SET x.state = d.state, x.lat = d.lat, x.lon = d.lon, x.bestMonths = d.months, x.description = d.description;\n")

    out.append("// STEP 3: Routes between destinations (ROUTE, one per travel mode)\n"
               "// Stored once and queried without direction. mode, distanceKm, hours and costInr are properties.")
    rs = [{"a": a, "b": b, "mode": m, "km": km, "hours": h, "cost": c} for a, b, m, km, h, c in T.ROUTES]
    out.append(f"UNWIND {rows(rs)} AS r\nMATCH (a:Destination {{name: r.a}})\nMATCH (b:Destination {{name: r.b}})\n"
               "MERGE (a)-[x:ROUTE {mode: r.mode}]->(b)\nSET x.distanceKm = r.km, x.hours = r.hours, x.costInr = r.cost;\n")

    out.append("// STEP 4: Attractions, their destination (LOCATED_IN) and categories (HAS_CATEGORY)")
    at = [{"id": i, "name": n, "dest": d, "cats": c, "rating": r, "fee": f, "hours": h} for i, n, d, c, r, f, h in T.ATTRACTIONS]
    out.append(f"UNWIND {rows(at)} AS a\nMATCH (d:Destination {{name: a.dest}})\nMERGE (x:Attraction {{attractionId: a.id}})\n"
               "SET x.name = a.name, x.rating = a.rating, x.entryFeeInr = a.fee, x.visitHours = a.hours\n"
               "MERGE (x)-[:LOCATED_IN]->(d)\nWITH x, a\nUNWIND a.cats AS cat\nMATCH (c:Category {name: cat})\n"
               "MERGE (x)-[:HAS_CATEGORY]->(c);\n")

    out.append("// STEP 5: Hotels (fictional) in each destination")
    hs = [{"id": i, "name": n, "dest": d, "stars": st, "price": p, "band": b, "rating": r, "amenities": am}
          for i, n, d, st, p, b, r, am in T.HOTELS]
    out.append(f"UNWIND {rows(hs)} AS h\nMATCH (d:Destination {{name: h.dest}})\nMERGE (x:Hotel {{hotelId: h.id}})\n"
               "SET x.name = h.name, x.stars = h.stars, x.pricePerNight = h.price, x.priceBand = h.band,\n"
               "    x.rating = h.rating, x.amenities = h.amenities\nMERGE (x)-[:LOCATED_IN]->(d);\n")

    out.append("// STEP 6: Tourists (fictional), their home city (LIVES_IN) and interests (INTERESTED_IN)")
    ts = [{"id": i, "name": n, "age": a, "home": h, "budget": b, "style": st,
           "interests": [{"cat": c, "w": w} for c, w in it.items()]} for i, n, a, h, b, st, it in T.TOURISTS]
    out.append(f"UNWIND {rows(ts)} AS t\nMATCH (home:Destination {{name: t.home}})\nMERGE (x:Tourist {{touristId: t.id}})\n"
               "SET x.name = t.name, x.age = t.age, x.budget = t.budget, x.travelStyle = t.style\n"
               "MERGE (x)-[:LIVES_IN]->(home)\nWITH x, t\nUNWIND t.interests AS i\nMATCH (c:Category {name: i.cat})\n"
               "MERGE (x)-[r:INTERESTED_IN]->(c)\nSET r.weight = i.w;\n")

    out.append("// STEP 7: Visits with ratings (VISITED)\n// Generated from interests with a fixed seed, so similar tourists overlap.")
    vs = [{"t": t, "a": a, "date": d, "rating": r} for t, a, d, r in T.VISITS]
    out.append(f"UNWIND {rows(vs)} AS v\nMATCH (t:Tourist {{touristId: v.t}})\nMATCH (a:Attraction {{attractionId: v.a}})\n"
               "MERGE (t)-[x:VISITED]->(a)\nSET x.date = date(v.date), x.rating = v.rating;\n")

    out.append("// STEP 8: Hotel stays (STAYED_AT) and wishlists (WISHLISTED)")
    st = [{"t": t, "h": h, "date": d, "nights": n, "rating": r} for t, h, d, n, r in T.STAYS]
    out.append(f"UNWIND {rows(st)} AS s\nMATCH (t:Tourist {{touristId: s.t}})\nMATCH (h:Hotel {{hotelId: s.h}})\n"
               "MERGE (t)-[x:STAYED_AT]->(h)\nSET x.date = date(s.date), x.nights = s.nights, x.rating = s.rating;\n")
    ws = [{"t": t, "d": d, "added": a} for t, d, a in T.WISHLIST]
    out.append(f"UNWIND {rows(ws)} AS w\nMATCH (t:Tourist {{touristId: w.t}})\nMATCH (d:Destination {{name: w.d}})\n"
               "MERGE (t)-[x:WISHLISTED]->(d)\nSET x.added = date(w.added);\n")

    out.append("// STEP 9: Check the result")
    out.append("MATCH (n)\nRETURN labels(n)[0] AS label, count(*) AS nodes ORDER BY nodes DESC;\n")
    out.append("MATCH ()-[r]->()\nRETURN type(r) AS relationship, count(*) AS total ORDER BY total DESC;\n")
    return "\n".join(out)


def inline(cypher):
    """Replace every $parameter with its sample value, so a query runs on its own in Neo4j Browser."""
    def repl(m):
        name = m.group(1)
        if name not in SAMPLE_PARAMS:
            raise ValueError(f"No sample value for ${name}")
        return s(SAMPLE_PARAMS[name])
    text = re.sub(r"\$(\w+)", repl, cypher)
    assert "$" not in text, text
    return text


def queries():
    values = ", ".join(f"{k} = {s(v)}" for k, v in SAMPLE_PARAMS.items() if k != "hidden")
    out = [f"""// =====================================================================
// TripGraph - all Cypher queries used by the application, ready to run in Neo4j Browser
// Generated by backend/tools/generate_cypher.py from backend/core/catalog.py
//
// Run scripts 01 and 02 first. Then run one STEP at a time (or the whole file).
// No parameters are needed: the sample values are written into each query.
// Change the quoted values to try other tourists, destinations or categories.
// Sample values used: {values}.
// Leg limits use 5 and routes optimise hours.
// The application runs the same queries with $parameters instead of fixed values.
// ====================================================================="""]
    section = None
    titles = {"model": "Model and data", "discover": "Destination discovery", "routes": "Routes and connections",
              "recommend": "Personalised recommendations"}
    for n, q in enumerate(QUERIES, 1):
        if q["section"] != section:
            section = q["section"]
            out.append(f"\n// ---------------- {titles[section]} ----------------")
        out.append(f"\n// STEP {n}: {q['title']}")
        for line in q["explain"]:
            if ";" in line:
                raise ValueError(f"Remove ';' from the explanation: {line}")
            out.append(f"//   - {line}")
        out.append(inline(q["cypher"].replace("{maxHops}", "5").replace("{metric}", "hours")) + ";")
    return "\n".join(out) + "\n"


RESET = """// =====================================================================
// TripGraph - delete ALL data. Constraints and indexes are kept.
// Run 02_sample_data.cypher again afterwards.
// =====================================================================

// STEP 1: Delete every node of the project and its relationships
MATCH (n)
WHERE n:Tourist OR n:Destination OR n:Attraction OR n:Category OR n:Hotel
DETACH DELETE n;
"""

if __name__ == "__main__":
    for name, text in (("01_constraints.cypher", constraints()), ("02_sample_data.cypher", sample()),
                       ("03_queries.cypher", queries()), ("99_reset.cypher", RESET)):
        with open(os.path.join(config.NEO4J_SCRIPTS_DIR, name), "w", encoding="utf-8") as fh:
            fh.write(text)
        print("wrote", name)
